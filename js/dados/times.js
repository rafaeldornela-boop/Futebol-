import { criarInstanciaHabilidade } from '../regras/habilidades.js';
import { garantirDesenvolvimentoJogador } from '../jogador/desenvolvimento.js';

function criarJogador({
  id,
  nome,
  nomeCurto,
  posicao,
  papel,
  setor = null,
  ehGoleiro = false,
  ehReserva = false,
  iniciaComBola = false,
  habilidades = [],
  idade = 24,
  peDominante = 'direito',
  qualidadePeFraco = 2,
  concentracao = 46,
  potencial = 62,
  curvaDesenvolvimento = 'equilibrada',
  caracteristicas = [],
  familiaridade = null,
  atributos,
}) {
  const dibrePadrao = ehGoleiro
    ? Math.max(18, Math.round((atributos.tecnica || 30) * 0.55))
    : ['PE', 'PD'].includes(posicao)
      ? Math.min(95, (atributos.tecnica || 48) + 5)
      : ['ME', 'MD'].includes(posicao)
        ? Math.min(94, (atributos.tecnica || 46) + 2)
        : ['ZAG'].includes(posicao)
          ? Math.max(20, (atributos.tecnica || 34) - 6)
          : atributos.tecnica || 42;

  const jogador = {
    id,
    nome,
    nomeCurto,
    posicao,
    papel,
    setor: setor || (ehGoleiro ? 'GOL' : null),
    ehGoleiro,
    iniciaComBola,
    idade,
    peDominante,
    qualidadePeFraco,
    potencial,
    curvaDesenvolvimento,
    nivelObservacao: 2,
    caracteristicas: [...caracteristicas],
    ...(familiaridade ? { familiaridade } : {}),
    zona: ehReserva ? null : ehGoleiro ? 'GK' : 'Z1-C',
    zonaBase: ehReserva ? null : ehGoleiro ? 'GK' : 'Z1-C',
    atributos: {
      passe: atributos.passe,
      dominio: atributos.dominio,
      posicionamento: atributos.posicionamento,
      marcacao: atributos.marcacao,
      interceptacao: atributos.interceptacao,
      desarme: atributos.desarme,
      velocidade: atributos.velocidade,
      tecnica: atributos.tecnica,
      dibre: atributos.dibre ?? dibrePadrao,
      finalizacao: atributos.finalizacao,
      agressividade: atributos.agressividade,
      concentracao,
      ...(ehGoleiro ? { defesa: atributos.defesa } : {}),
    },
    mental: {
      concentracao,
    },
    extras: {
      estamina: 100,
      habilidades: habilidades.map(criarInstanciaHabilidade).filter(Boolean),
      cartoes: { amarelos: 0, vermelho: false },
      substituido: false,
    },
  };

  return garantirDesenvolvimentoJogador(jogador);
}

